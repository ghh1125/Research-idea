"""Safe, actionable provider failures; raw provider messages never reach logs."""
from __future__ import annotations

import json
import re

from .backend_types import BackendError


ERROR_LABELS = {
    'network': ('网络连接失败', '请检查网络或代理连接。'),
    'timeout': ('模型响应超时', '可用 /budget timeout_s 调整单次等待时间。'),
    'model': ('模型不可用或无访问权限', '用 /model、/models 核对模型 ID 和账户权限。'),
    'auth': ('登录或 API 认证失败', '用 /account 查看登录方式，检查 CLI 登录或 API 密钥。'),
    'quota': ('余额或可用额度不足', '请检查服务商余额、用量上限或订阅额度。'),
    'rate_limit': ('请求过于频繁', '服务商正在限流。'),
    'permission': ('接口访问被拒绝', '请检查账户权限和接口地址。'),
    'server': ('模型服务暂时异常', '服务商返回了服务器错误。'),
    'api': ('API 请求失败', '请检查接口地址和请求配置。'),
    'backend': ('模型调用失败', '可用 /account、/model 检查后端设置。'),
}


def classify_provider_error(details='', status=None):
    """Use provider codes/messages only for classification, never echo them."""
    text = (json.dumps(details, ensure_ascii=False) if isinstance(details, (dict, list)) else str(details)).lower()
    if re.search(r'insufficient[_ ](?:quota|funds|credits|balance)|credit balance|out of credits|billing[_ ]hard[_ ]limit|exceeded your current quota|usage limit|spending limit|quota exceeded|余额不足|额度已用完', text) or status == 402:
        return 'quota'
    if re.search(r'model[_ -]not[_ -]found|invalid[_ -]model|unsupported[_ -]model|model[^\n]{0,100}(?:does not exist|not supported|not available|unavailable|not found)|(?:access|permission)[^\n]{0,80}(?:to|for) (?:this |the )?model', text):
        return 'model'
    if re.search(r'invalid[_ -](?:api[_ -]?key|authentication)|authentication[_ -]error|unauthorized|not logged in|token[_ ]expired|expired.*token|incorrect api key', text) or status == 401:
        return 'auth'
    if re.search(r'rate[_ -]?limit|too many requests', text) or status == 429:
        return 'rate_limit'
    if re.search(r'timed? ?out|timeout', text) or status in {408, 504}:
        return 'timeout'
    if re.search(r'connection (?:failed|refused|reset)|network|stream disconnected|unable to connect|dns|name resolution', text):
        return 'network'
    if status == 403:
        return 'permission'
    if (isinstance(status, int) and 500 <= status <= 599) or re.search(r'overloaded|server_error|internal server error', text):
        return 'server'
    return 'api' if isinstance(status, int) else 'backend'


class ProviderError(BackendError):
    """A failed provider attempt that can be retried without changing the task."""

    def __init__(self, category='backend', *, status=None, transport_attempts=None, diagnostic=''):
        self.category = category if category in ERROR_LABELS else 'backend'
        self.status = status if type(status) is int else None
        self.transport_attempts = transport_attempts
        label, action = ERROR_LABELS[self.category]
        message = f'[{self.category}] {label}' + (f'（HTTP {self.status}）' if self.status else '') + '。' + action
        # diagnostic must be generated by our adapters, never provider text.
        super().__init__(message + (' ' + diagnostic if diagnostic else ''))


class RetryExhausted(BackendError):
    def __init__(self, error: ProviderError, retries: int):
        self.category, self.status, self.retries = error.category, error.status, retries
        super().__init__(f'{error}\n重试 {retries} 次后仍失败，当前任务已结束；进度已保存。处理问题后，研究用 /run 继续，讨论可重新发送消息。')
