"""First-phase procedures: synthesize a research problem, then form an idea.

Keep these as complete procedures rather than accumulating overlapping review
checklists. Source-level audits remain in the reader and the supplied evidence.
"""

PROBLEM_ORIGIN_RULES = """
研究问题只从两条推导路线引出，按实际主因选择 problem_origin；它说明问题怎样产生，不是给已选方法贴标签：
1. unresolved_need：从已有的重要需要出发，说明现有主要路线已经推进到哪里，在什么实际条件下仍留下哪项能力障碍，以及为什么正常使用这些方法仍跨不过它。问题首先是这项障碍及其后果，不是缺少我们准备增加的操作。
2. emerging_problem：从已有方法的一项使用、扩展或发展出发，说明这个变化怎样产生或暴露原先不突出的问题，它损害什么能力，以及原有解决思路为什么不能顺带处理。要有“变化 → 困难 → 重要后果”的推导，不能只说一个新方法可能更好。
两条路线都允许基于证据和机制提出有理由的研究假设，不要求先有实验结论。“现有方法不保证做到”“没有显式采用我们的操作”“还没有测过”本身都不能代替重要障碍；论文矛盾、跨领域启发和能力边界是发现问题的线索，不是第三种来源。
比较实际目标、可用信息、正常操作和结论，不凭标题、作者的大范围 claim 或检索遗漏断言问题已经解决或全领域无人解决。若最接近方法的正常使用已经满足所述需要，就重新推导值得研究的具体问题；解释研究同样需要独立成立的重要未知关系，不能把它当作保留原方案的通用退路。
"""

MAP_INSTRUCTIONS = """
这一步要把文献提炼成一个值得研究的问题。先理解用户的大课题，再找问题的根本；不要从某篇论文的实验里挑一个小因素作为我们的研究方向。尊重 user_notes 中的最新研究意图与明确范围。

先建立 research_frame：
- user_goal：用普通话说明用户最终希望模型或研究者能做到什么，以及为什么需要这件事。
- literature_logic：把有关工作按解决思路串起来，说明它们怎样回应背景需要、已经实现什么，再沿两条问题来源中的一条推导仍存在或新出现的关键障碍及后果。按研究逻辑组织段落，论文为论点提供依据，不逐篇罗列摘要，也不把“未采用拟议操作”当作共同局限。
- research_question：先确定独立于候选方法的重要问题，具体到什么能力或认识在什么条件下仍受阻。它应由 literature_logic 推出；不能先选操作，再把操作想改善的指标定义成用户的大目标。
- scope_connection：解释源论文的具体结果为什么能启发这个大问题，哪些是结果、哪些是我们的进一步推论。实验场景作为依据保留，不自动成为用户的研究范围。

接着在 opportunities 中保留两到三个真正不同、值得考虑的方向；最多四个，不凑数。每个方向包含：
- id、question、problem_origin、basis；basis 为 source_observation 时须有来源依据，为 research_hypothesis 时把问题或原因作为我们提出的判断。
- derivation：在提出 insight 之前，沿所选 problem_origin 推导这项具体问题。说明背景需要怎样经过已有进展与实际条件，落到这项独立于候选方法的障碍，以及为什么它对用户目标重要；不能靠方法缺少拟议操作、没有保证或没有报告来补出问题。
- insight：从这个原因得出一个不显然的认识，以及它提示应该改变什么基本做法。先有问题的必要性，再有解决它的想法。
- why_it_matters：解决后能多做到什么，或对这个大课题会产生什么新的理解。即使换掉喜欢的技术，这个问题也应值得研究。
- prior_art_delta：认真考虑最接近方法的正常用法，包括其已有的更新和主动获取信息。说明它为什么仍未回答这里的核心问题。已有方法可以借鉴；方法相似不等于动机和贡献重合。
- feasibility_basis：谁能改变什么、需要哪些可获得的信息、为什么这条思路有可能起作用。不要靠额外隐藏信息、任意限制或未知接口制造一个问题。
- evidence_ids 和 closest_work_ids：只使用已提供的真实 ID。借助 paper_cards 和 paper_claim_audits 回到原文细节；作者的大范围 claim 不等于实验已经解决了大范围问题，证据不足也不让已有机制重新变新。

比较方向时先看 derivation 揭示了哪项重要障碍、解决它怎样推进用户目标，再考虑洞见和获取信息的路径如何使研究可着手。信息容易取得、技术容易实现或变量容易隔离，都不能反过来替问题制造必要性。可以在当前任务内改进方向，不增加评分或审查轮次。
比较这些方向时，把最有希望的核心操作向前推演一步：究竟作用于哪些对象、关系或信号，它们怎样从实际输入得到，操作会让系统必须学会或做到什么。不能只把“利用隐藏关系、构造可靠反馈、选择有用信息”作为核心洞见，而把如何得到这些东西留给以后。可行路径可以是研究者提出的新办法，但要讲出由输入到操作的过程。若这一步与最接近方法的正常使用相同，就继续寻找有实质意义的解释或能力差异；不要仅把贡献换成一个更大的说法。
problem、observations、competing_explanations、unresolved_questions 总结上述分析；opportunity_types 为 opportunities 中实际使用的 problem_origin 去重列表。每个方向的字段用一两句有内容的话说明，research_frame 用连贯段落讲透逻辑。正文不列基准参数、数值结果或实验方案，必要的来源条件放在 scope_connection 与证据中。
""" + PROBLEM_ORIGIN_RULES

PROPOSE_INSTRUCTIONS = """
交付第一阶段的研究 idea，到 Background → Problem → Motivation → Idea 为止。第二阶段再探索技术参考；这里不写具体例子、实现规格或实验计划。

从 problem_model.research_frame 和 opportunities 先选择最值得解决的重要障碍，再用洞见和可行路径说明怎样着手，记录 opportunity_id。selection_reason 解释为何优先研究这项障碍、它对背景目标有什么实质影响，再说明核心认识和路径的作用；不能仅凭方法新鲜、信息可得或符合主题选中。motivation.problem_origin 必须与所选 opportunity 的 problem_origin 一致。可以改进洞见与操作，但不把另一项问题冒充这条来源。max_candidates 是上限，通常只交付最有说服力的一个。

把 motivation 写成一条完整论证，让读者顺着上一步理解下一步：
1. background：从用户面对的大背景和实际需要讲起。不要一上来规定某篇论文的数据、标签形式或任务，也不为适配候选方法而提前改写用户目标。用普通话说清为什么需要继续研究这件事。
2. existing_work：综合几条已有解决思路，讲清它们帮助我们做到了什么，以及共同依赖什么。按思路组织；具体论文的逐项比较放在 positioning。
3. problem_origin + problem_derivation：沿所选 opportunity 的来源与 derivation，用一个连贯段落解释为什么从上述背景和已有进展，选择眼前这项具体问题。unresolved_need 写清实际条件下仍未解决的障碍；emerging_problem 写清已有方法的使用或发展怎样产生新困难。这里承担背景到问题的真实过渡，不重复背景口号，也不介绍拟议方法。problem_observation 明确推导出的同一项困难，importance 说明它的后果；新提出的困难可以是有理由的研究假设。
4. causal_explanation + existing_approach_limit：解释问题为什么会存在，以及现有思路的目标、信息或工作方式为什么无法自然消除它。把问题上升为可理解的根本原因，而不是某篇论文写法的缺点。用原文细节检验推理，同时承认已有方法真正能做的事。
5. research_need：承接 problem_derivation 和 problem_observation 中的同一障碍，说明因此必须理解什么关系、改变什么原则或实现什么能力，才会推进背景目标。先讲研究需要，再谈可选技术；不能把“需要增加我们的方法”当动机，也不能在这里悄悄换成另一项问题。
6. why_this_method：据此提出核心 idea：准备让谁利用什么信息、改变什么做法，为什么能作用于刚才的原因。讲清实际发生的改变和作用原理，避免只说“更好挖掘”“自适应利用”。这是有方向的想法，不是完整技术方案。
7. expected_progress：解释实现这个想法后，人们能多做什么或理解什么。不要把一般涨分、格式变化、增加模块或重新命名的取舍直接当作贡献。

把核心想法在 idea_core 中讲到可理解、可推演，而不展开技术实现或实验：
- concrete_target：具体利用、改变或解释的是什么？说明涉及的对象、对象之间的关系或可观察信号，以及它在什么条件下有意义。“潜在关系”“新模式”“有用信息”只是类别，必须进一步说明内容。聚焦操作对象不等于把大问题缩成某个数据集。
- construction_path：这些对象、关系或信号从哪里来，谁怎样从已有输入识别、构造或核对？明确哪些直接观察、哪些由规则推得、哪些是模型估计。若估计本身可能错，说明为何仍能形成有效的学习或判断依据，避免用同一个未经检验的猜测既产生答案又证明自己正确。不要把核心难点外包给“训练者先确认可靠关系”或“自动生成正确监督”；提出实际可用的获取路径。简述关键成立条件即可。
- capability_bridge：先说明相对原流程，核心操作新增或改变了哪项实际学习或判断要求。仅重排材料或并列展示，而学习要求、反馈和操作约束未变，不能仅凭呈现方式宣称新机制。再解释系统现在需要学会或做到什么，以及这怎样对应用户希望获得的能力或新认识。考虑一种同样能完成表面任务、却没有学到目标能力的简单办法，说明当前设计在信息、反馈或判断要求上如何区别二者；不要只把这个问题留成以后验证。对于不训练的 idea，说明决策或信息使用过程怎样改变。保留关键因果假设，不从“增加一致性/多一种任务”直接跳到“获得泛化能力”。用文字讲明作用即可，不要求具体损失公式或实验计划。
- essential_difference：选最接近的已读方法，说明它在正常使用、拥有相同可用信息时已经能做到什么；我们的改变究竟在哪个信息、操作、目标或解释上，以及为什么会产生不同的能力或认识。与 positioning 的逐篇依据一致。区分论文为了分析而采用的理论假设与算法实际运行所需的信息或条件，不能把推导中的理想条件当成实现依赖来制造差异。若来源材料不足以确定某项细节，明确比较的实际依据和我们的推论，不用“别人没有研究”填空。允许沿用已有技术，但必须讲清新的问题或知识贡献；换术语、增加要求、多个已有目标拼起来不自动构成实质差异。

why_this_method 简明概括想法，idea_core 展开上述四个相互衔接的回答，避免反复重述。它们是第一阶段要交付的核心内容，不留到第二阶段才解释。若发现操作其实依赖拿不到的信息、能力跳跃或正常使用已有方法就能解决，在当前构思内修改 idea；不增加拒绝门槛或额外审查轮次。

每部分用足够的完整句子展开，避免抽象名词堆叠和重复同一句重要性。标题能让人看懂核心问题；background 不应要求读者先了解源论文。论文的测试任务只是支撑局部判断的依据；除非用户主动限定，idea 不能被这些任务替代。大课题允许聚焦到一个关键障碍，聚焦后仍要说明解决它怎样推进大课题。

在当前构思中完成贡献对照：对每个 closest_work_id 给出 positioning，说明 addressed_problem、remaining_question、contribution，并引用这篇论文的 evidence_ids。相似主题或技术可以带来有用借鉴；只有具体问题、动机与所要回答的贡献相重合，才需要改变切入点。不要用作者的 claim 代替实验细节，也不要把缺少实验支持当成机制的新颖性。已有方案若正常使用就能解决问题，应加强问题认识或换一个更有意义的方向，而不是添加人为限制来保护原方案。

用 feasibility_sketch 简短推演可获得的输入、可操作的改变及它们如何产生作用，修掉可提前发现的信息循环或不可获取的依赖。key_assumption 与 first_check 仅说明关键假设和判断它所需的概念性证据，不展开实验。hypothesis、mechanism、intervention、prediction、falsifier 与主论证保持一致；后两者是研究判断，不是实验计划。motivation.simplest_alternative 与 necessity_test 只作简短内部推敲。
基于原文的事实引用真实 evidence_ids；basis 区分源论文观察和我们的研究假设。新的解释直接说“我们怀疑”，不在正文反复使用“所供材料”“尚未确认”“没有建立为已观察事实”。大胆提出一个有理由的想法，实验尚未进行、资料范围有限、方法可以借鉴，都不是停止构思的理由。no_candidate_reason 通常为空；只有题目本身存在无法调和的明确矛盾才不交付候选。
""" + PROBLEM_ORIGIN_RULES
